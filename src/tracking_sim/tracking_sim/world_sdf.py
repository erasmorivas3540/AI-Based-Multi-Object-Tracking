"""Write a Gazebo Harmonic (SDF 1.9) world for one flight.

Every object whose pose changes is a non-static model with gravity off and no
collision geometry; the director teleports it every frame through UserCommands'
set_pose_vector service. Clutter and the ground are static.

The observer carries three sensors with identical intrinsics:
  rgb            camera                       -> frames
  boxes_visible  boundingbox_camera, 2d        -> Gazebo's visible 2D boxes (audit)
  boxes_full     boundingbox_camera, full_2d   -> Gazebo's full-extent boxes (audit)
Target models carry the Label system (label = persistent target id) so the
bounding-box cameras report them.

UNVERIFIED in this repository's CI (Gazebo is not installable there). Run
scripts/gz_render_flight.py --max-frames 40 and the audit before trusting it; see
docs/gazebo_verification.md.
"""
from __future__ import annotations

from pathlib import Path
from xml.sax.saxutils import escape

import numpy as np

from .scenario import Scenario
from .shapes import PLAIN, SHAPES

WORLD_NAME = "flight"
STEP_S_DEFAULT = 0.05   # one physics step per camera frame at 20 fps


def _box_visual(name, offset, size, rgb):
    r, g, b = rgb
    return f"""
        <visual name="{escape(name)}">
          <pose>{offset[0]} {offset[1]} {offset[2]} 0 0 0</pose>
          <geometry><box><size>{size[0]} {size[1]} {size[2]}</size></box></geometry>
          <material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse><specular>0.1 0.1 0.1 1</specular></material>
        </visual>"""


def _camera_block(cam, near=0.1, far=2000.0, extra=""):
    return f"""<camera>
            <horizontal_fov>{cam.hfov_rad:.8f}</horizontal_fov>
            <image><width>{cam.width}</width><height>{cam.height}</height><format>R8G8B8</format></image>
            <clip><near>{near}</near><far>{far}</far></clip>{extra}
          </camera>"""


def _pose(pos, yaw=0.0, pitch=0.0, roll=0.0):
    return f"{pos[0]:.4f} {pos[1]:.4f} {pos[2]:.4f} {roll:.6f} {pitch:.6f} {yaw:.6f}"


def world_xml(sc: Scenario, cfg: dict, step_s: float = STEP_S_DEFAULT) -> str:
    cam = sc.cam
    fps = cfg["clip"]["fps"]
    ground_rgb = [c / 255 for c in cfg["layouts"][sc.clip["layout"]]["ground_rgb"]]
    models = []

    # ------------------------------------------------------------ observer + sensors
    models.append(f"""
    <model name="observer">
      <pose>{_pose(sc.cam_pos[0], *sc.cam_ypr[0])}</pose>
      <link name="link">
        <gravity>false</gravity>
        <sensor name="rgb" type="camera">
          <always_on>1</always_on><update_rate>{fps}</update_rate><topic>observer/rgb</topic>
          {_camera_block(cam)}
        </sensor>
        <sensor name="boxes_visible" type="boundingbox_camera">
          <always_on>1</always_on><update_rate>{fps}</update_rate><topic>observer/boxes_visible</topic>
          {_camera_block(cam, extra="<box_type>2d</box_type>")}
        </sensor>
        <sensor name="boxes_full" type="boundingbox_camera">
          <always_on>1</always_on><update_rate>{fps}</update_rate><topic>observer/boxes_full</topic>
          {_camera_block(cam, extra="<box_type>full_2d</box_type>")}
        </sensor>
      </link>
    </model>""")

    # ------------------------------------------------------------ dynamic objects
    for o in sc.objects:
        if o.kind == "clutter":
            continue
        pos, yaw, pitch = o.pose_at(0)
        if o.kind == "target":
            visuals = "".join(_box_visual(p["name"], p["offset"], p["size"], p["rgb"]) for p in SHAPES[o.cls])
            label = f"""
      <plugin filename="gz-sim-label-system" name="gz::sim::systems::Label"><label>{o.obj_id}</label></plugin>"""
        else:
            visuals = _box_visual("panel", (0, 0, 0), o.size, PLAIN["occluder"])
            label = ""
        models.append(f"""
    <model name="{o.name}">
      <pose>{_pose(pos, yaw, pitch)}</pose>
      <link name="link"><gravity>false</gravity>{visuals}
      </link>{label}
    </model>""")

    # ------------------------------------------------------------ static clutter
    for o in sc.objects:
        if o.kind != "clutter":
            continue
        pos, yaw, _ = o.pose_at(0)
        models.append(f"""
    <model name="{o.name}"><static>true</static>
      <pose>{_pose(pos, yaw)}</pose>
      <link name="link">{_box_visual("box", (0, 0, 0), o.size, PLAIN["clutter"])}
      </link>
    </model>""")

    gr, gg, gb = ground_rgb
    return f"""<?xml version="1.0"?>
<!-- Generated by tracking_sim.world_sdf for flight {escape(sc.clip['flight_id'])}. Do not edit by hand. -->
<sdf version="1.9">
  <world name="{WORLD_NAME}">
    <physics name="frame_step" type="ignored">
      <max_step_size>{step_s}</max_step_size>
      <real_time_factor>0</real_time_factor>
    </physics>
    <gravity>0 0 -9.81</gravity>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <scene>
      <ambient>0.55 0.55 0.55 1</ambient>
      <background>0.67 0.75 0.80 1</background>
      <grid>false</grid>
      <shadows>true</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 100 0 0 0</pose>
      <diffuse>0.85 0.85 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.25 -0.9</direction>
    </light>
    <model name="ground"><static>true</static>
      <link name="link">
        <visual name="plane">
          <geometry><plane><normal>0 0 1</normal><size>4000 4000</size></plane></geometry>
          <material><ambient>{gr} {gg} {gb} 1</ambient><diffuse>{gr} {gg} {gb} 1</diffuse></material>
        </visual>
      </link>
    </model>{''.join(models)}
  </world>
</sdf>
"""


def write_world(sc: Scenario, cfg: dict, path: Path, step_s: float = STEP_S_DEFAULT) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(world_xml(sc, cfg, step_s))
    return path


def quat_from_ypr(yaw: float, pitch: float, roll: float):
    """(w, x, y, z) for R = Rz(yaw) Ry(pitch) Rx(roll)."""
    cy, sy = np.cos(yaw / 2), np.sin(yaw / 2)
    cp, sp = np.cos(pitch / 2), np.sin(pitch / 2)
    cr, sr = np.cos(roll / 2), np.sin(roll / 2)
    return (cr * cp * cy + sr * sp * sy, sr * cp * cy - cr * sp * sy,
            cr * sp * cy + sr * cp * sy, cr * cp * sy - sr * sp * cy)


def frame_poses(sc: Scenario, f: int) -> list[tuple]:
    """[(model_name, (x,y,z), (w,x,y,z)), ...] for every moving model at frame f."""
    out = [("observer", tuple(sc.cam_pos[f]), quat_from_ypr(*sc.cam_ypr[f]))]
    for o in sc.objects:
        if o.kind == "clutter":
            continue
        pos, yaw, pitch = o.pose_at(f)
        out.append((o.name, tuple(pos), quat_from_ypr(yaw, pitch, 0.0)))
    return out
